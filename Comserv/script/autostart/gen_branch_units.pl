#!/usr/bin/perl
# Generate one systemd --user unit per worktree in root/config/worktrees.json.
#
# Why: BranchServerControl already prefers `systemctl --user` over spawning a bare
# perl when a unit named comserv-<branch>-<port>.service exists (unit_name()). Only
# :4006 has one, so every other branch server runs as a hand-spawned `perl ... -r`
# whose Catalyst restarter leaves several generations per port and frequently serves
# STALE code while a newer process failed to bind. Units make start/stop/restart
# deterministic (one process, port released before start), which is what the Git
# dashboard's Restart/Open buttons and the bulk update's "restart once at the end"
# both need.
#
# Usage:  perl script/autostart/gen_branch_units.pl [--install]
#         (default: write the files and PRINT the commands; --install runs
#          `systemctl --user daemon-reload` and prints enable instructions only)
use strict; use warnings;
use JSON::MaybeXS qw(decode_json);
use File::Path qw(make_path);

my $root = $0;
$root =~ s{script/autostart/gen_branch_units\.pl$}{} or die "run this from the Comserv app dir\n";
my $cfg_file = $root . 'root/config/worktrees.json';
open my $fh, '<', $cfg_file or die "cannot read $cfg_file: $!\n";
local $/; my $cfg = decode_json(<$fh> // '{}'); close $fh;

my $home  = $ENV{HOME} or die "no HOME\n";
my $base  = $cfg->{base_dir} // "$home/.comserv/worktrees";
my $dir   = "$home/.config/systemd/user";
my $perl  = '/home/shanta/perl5/perlbrew/perls/perl-5.40.0/bin/perl';
my $lib   = '/home/shanta/perl5/lib/perl5';
make_path($dir);
make_path("$home/.comserv/logs");

my $install = (@ARGV && $ARGV[0] eq '--install') ? 1 : 0;
my $wrote = 0;
for my $key (sort keys %{ $cfg->{branches} // {} }) {
    my $ent  = $cfg->{branches}{$key};
    my $port = ref $ent eq 'HASH' ? $ent->{port} : $ent;
    next unless defined $port && $port =~ /^\d+$/;
    my $wd = "$base/$key/Comserv/Comserv";
    unless (-d $wd) { warn "skip $key : $wd is not a checkout\n"; next; }

    my $name = "comserv-$key-$port.service";
    my $txt = <<"UNIT";
# Generated by script/autostart/gen_branch_units.pl from root/config/worktrees.json.
# :$port = $key worktree. No -r: the process is supervised here (Restart=on-failure),
# so a bulk main merge cannot trigger a restart storm mid-merge; the Git dashboard
# restarts the unit once when the merge is done.
[Unit]
Description=Comserv $key dev server on :$port (branch $key)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$wd
Environment=CATALYST_DEBUG=1
Environment=COMSERV_NO_HEALTH_LOG=1
Environment=PERL5LIB=$lib
Environment=PATH=/home/shanta/perl5/perlbrew/perls/perl-5.40.0/bin:/usr/local/bin:/usr/bin:/bin
# Wait out a hand-started server still holding the port (stop can lag a few seconds);
# without this every restart silently skipped.
ExecCondition=/bin/sh -c 'i=0; while ss -ltn | grep -q ":$port "; do i=\$\$((i+1)); [ \$\$i -ge 20 ] && exit 1; sleep 1; done; exit 0'
ExecStart=$perl script/comserv_server.pl -p $port
Restart=on-failure
RestartSec=5
StandardOutput=append:$home/.comserv/logs/$key\_$port.log
StandardError=append:$home/.comserv/logs/$key\_$port.log

[Install]
WantedBy=default.target
UNIT
    open my $o, '>', "$dir/$name" or die "cannot write $dir/$name: $!\n";
    print $o $txt; close $o;
    $wrote++;
    print "wrote $dir/$name\n";
}

print "\n$wrote unit(s) written. To use them (one branch at a time, while it is stopped):\n";
print "  systemctl --user daemon-reload\n";
for my $key (sort keys %{ $cfg->{branches} // {} }) {
    my $ent = $cfg->{branches}{$key};
    my $port = ref $ent eq 'HASH' ? $ent->{port} : $ent;
    next unless defined $port && $port =~ /^\d+$/ && -d "$base/$key/Comserv/Comserv";
    print "  systemctl --user enable --now comserv-$key-$port.service\n";
}
print "\nStop the hand-started server for a port FIRST (it holds the port and ExecCondition\nwill refuse), e.g. from the Git dashboard's Develop Servers card, or:\n  pkill -f 'comserv_server.pl -p 4004'\n";
if ($install) { system(qw(systemctl --user daemon-reload)); print "\ndaemon-reload done.\n"; }
