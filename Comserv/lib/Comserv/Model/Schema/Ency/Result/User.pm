# Add method to check password (PBKDF2-aware; auto-upgrades legacy SHA-256)
sub check_password {
    my ($self, $password) = @_;

    my $stored = $self->password || '';
    return 0 unless $stored;

    # PBKDF2 hashes generated by Crypt::PBKDF2 start with '{X-PBKDF2}'
    if (index($stored, '{X-PBKDF2}') == 0) {
        my $pbkdf2 = Crypt::PBKDF2->new;
        return $pbkdf2->validate($stored, $password);
    }

    # Legacy SHA-256 hashes are 64 hex characters
    if ($stored =~ /^[0-9a-fA-F]{64}$/) {
        use Digest::SHA qw(sha256_hex);
        my $hashed_input = sha256_hex($password);

        if ($stored eq $hashed_input) {
            # Correct legacy password: transparently upgrade to PBKDF2
            eval {
                my $pbkdf2 = Crypt::PBKDF2->new;
                my $new_hash = $pbkdf2->generate($password);
                $self->update({ password => $new_hash });
            };
            return 1;
        }
    }

    return 0;
}

# Class/instance helper to generate new PBKDF2 hashes
sub hash_password {
    my ($class_or_self, $password) = @_;
    my $pbkdf2 = Crypt::PBKDF2->new;
    return $pbkdf2->generate($password);
}

# Add method to get display name
sub display_name {
    my $self = shift;
    my $name = '';
    $name .= $self->first_name if $self->first_name;
    $name .= ' ' if $name && $self->last_name;
    $name .= $self->last_name if $self->last_name;
    return $name || $self->username;
}

